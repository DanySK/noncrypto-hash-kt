/**
 * Prevents benchmark programs from running concurrently, which would distort the measurements.
 */
abstract class BenchmarkLock : BuildService<BuildServiceParameters.None>

val benchmarkLock = gradle.sharedServices.registerIfAbsent("benchmarkLock", BenchmarkLock::class) {
    maxParallelUsages = 1
}

/**
 * Writes to two streams, so that benchmark output is both shown and recorded.
 */
class TeeOutputStream(private val first: OutputStream, private val second: OutputStream) : OutputStream() {
    override fun close() {
        first.close()
        second.flush()
    }

    override fun flush() {
        first.flush()
        second.flush()
    }

    override fun write(b: Int) {
        first.write(b)
        second.write(b)
    }

    override fun write(b: ByteArray, off: Int, len: Int) {
        first.write(b, off, len)
        second.write(b, off, len)
    }
}

val rawOutputDirectory = layout.buildDirectory.dir("benchmarks/raw")

val runJvmBenchmark = tasks.register<JavaExec>("runJvmBenchmark") {
    group = "benchmark"
    description = "Runs the benchmarks on the JVM."
    val compilation = kotlin.jvm().compilations.getByName("main")
    classpath = files(compilation.output.allOutputs, compilation.runtimeDependencyFiles)
    mainClass = "org.danilopianini.noncryptohash.benchmarks.MainKt"
    javaLauncher = javaToolchains.launcherFor { languageVersion = JavaLanguageVersion.of(benchmarkJvm) }
    jvmArgs("-Xms2g", "-Xmx2g")
}

val nativeRunTask: String? = kotlin.targets.withType<KotlinNativeTarget>().singleOrNull()?.let {
    "runReleaseExecutable${it.name.replaceFirstChar(Char::uppercase)}"
}

/*
 * Target name -> task running its benchmark program.
 */
val runTasks: Map<String, String> = buildMap {
    put("jvm", runJvmBenchmark.name)
    put("js", "jsNodeProductionRun")
    put("wasmJs", "wasmJsNodeProductionRun")
    put("wasmWasi", "wasmWasiNodeProductionRun")
    nativeRunTask?.let { put("native", it) }
}.filterKeys { it in selectedTargets }

runTasks.forEach { (target, taskName) ->
    tasks.named(taskName) {
        group = "benchmark"
        usesService(benchmarkLock)
        val output = rawOutputDirectory.map { it.file("$target.txt") }
        outputs.file(output)
        outputs.upToDateWhen { false }
        doFirst {
            val file = output.get().asFile
            file.parentFile.mkdirs()
            (this as BaseExecSpec).standardOutput = TeeOutputStream(file.outputStream(), System.out)
        }
    }
    if (target == "js" || target == "wasmJs") {
        // Allows the programs to force garbage collections when measuring memory
        tasks.named<org.jetbrains.kotlin.gradle.targets.js.nodejs.NodeJsExec>(taskName) {
            nodeArgs += "--expose-gc"
        }
    }
}

/**
 * Describes the machine without identifying it: the results are published.
 */
fun machineDescription(): Map<String, Any?> {
    val os = System.getProperty("os.name")
    val cpu = runCatching {
        when {
            os == "Linux" -> File("/proc/cpuinfo").readLines()
                .firstOrNull { it.startsWith("model name") }
                ?.substringAfter(':')
                ?.trim()
            os.startsWith("Mac") -> ProcessBuilder("sysctl", "-n", "machdep.cpu.brand_string")
                .start().inputStream.bufferedReader().readText().trim()
            os.startsWith("Windows") -> System.getenv("PROCESSOR_IDENTIFIER")
            else -> null
        }
    }.getOrNull() ?: "unknown CPU"
    val memory = (ManagementFactory.getOperatingSystemMXBean() as? com.sun.management.OperatingSystemMXBean)
        ?.totalMemorySize
    return mapOf(
        "label" to providers.gradleProperty("benchmark.machine").getOrElse(cpu),
        "cpu" to cpu,
        "cores" to Runtime.getRuntime().availableProcessors(),
        "memoryBytes" to memory,
        "os" to os,
        "osVersion" to System.getProperty("os.version"),
        "arch" to System.getProperty("os.arch"),
    )
}

fun git(vararg arguments: String): String? = runCatching {
    providers.exec { commandLine("git", *arguments) }.standardOutput.asText.get().trim()
}.getOrNull()

/**
 * Parses the lines `BENCHMARK <kind> <json>` printed by a benchmark program.
 */
fun parseTarget(target: String, file: File): Map<String, Any?> {
    val slurper = JsonSlurper()
    val records = file.readLines()
        .filter { it.startsWith("BENCHMARK ") }
        .map { line ->
            val (_, kind, json) = line.split(' ', limit = 3)
            kind to slurper.parseText(json)
        }
    val runtime = records.single { it.first == "runtime" }.second as Map<*, *>
    check(records.any { it.first == "end" }) { "The $target benchmark did not complete" }
    return mapOf(
        "target" to target,
        "runtime" to runtime["runtime"],
        "results" to records.filter { it.first == "result" }.map { it.second },
        "footprints" to records.filter { it.first == "footprint" }.map { it.second },
    )
}

tasks.register("benchmark") {
    group = "benchmark"
    description = "Runs the benchmarks on every selected target, and stores the results in docs/benchmarks."
    dependsOn(runTasks.values)
    val siteDirectory = rootProject.layout.projectDirectory.dir("docs/benchmarks")
    val outputDirectory = if (quick) layout.buildDirectory.dir("benchmarks/site") else provider { siteDirectory }
    outputs.upToDateWhen { false }
    // Computed by gitSemVer in the root project
    val projectVersion = rootProject.version.toString()
    doLast {
        val now = Instant.now()
        val machine = machineDescription()
        val slug = machine["label"].toString().lowercase().replace(Regex("[^a-z0-9]+"), "-").trim('-').take(40)
        val id = DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH-mm-ss'Z'").withZone(ZoneOffset.UTC).format(now) +
            "-$slug"
        val run = mapOf(
            "id" to id,
            "date" to now.toString(),
            "quick" to quick,
            "version" to projectVersion,
            "machine" to machine,
            "commit" to mapOf(
                "hash" to git("rev-parse", "HEAD"),
                "dirty" to git("status", "--porcelain")?.isNotEmpty(),
            ),
            "kotlin" to libs.versions.kotlin.get(),
            "targets" to runTasks.keys.map { target ->
                parseTarget(target, rawOutputDirectory.get().file("$target.txt").asFile)
            },
        )
        val output = outputDirectory.get().asFile
        if (quick) {
            // Quick runs are not published: preview them with a private copy of the site
            siteDirectory.asFile.listFiles { file -> file.isFile }?.forEach { it.copyTo(output.resolve(it.name), true) }
        }
        val results = output.resolve("results").apply { mkdirs() }
        results.resolve("$id.json").writeText(JsonOutput.prettyPrint(JsonOutput.toJson(run)) + "\n")
        val runs = results.listFiles { file -> file.extension == "json" && file.name != "index.json" }
            .orEmpty()
            .map { JsonSlurper().parse(it) as Map<*, *> }
            .sortedByDescending { it["date"].toString() }
        val index = runs.map {
            mapOf(
                "id" to it["id"],
                "date" to it["date"],
                "version" to it["version"],
                "machine" to (it["machine"] as Map<*, *>)["label"],
            )
        }
        results.resolve("index.json").writeText(JsonOutput.prettyPrint(JsonOutput.toJson(index)) + "\n")
        // Loaded by the site with a script tag, so that it also works from the file system
        output.resolve("data.js").writeText("window.BENCHMARK_RUNS = ${JsonOutput.toJson(runs)};\n")
        logger.lifecycle("Benchmark results: {}", output.resolve("index.html").toURI())
    }
}
