/*
 * Benchmarks of every hash function, on every target that can run on the current host.
 *
 * Usage:
 *   ./gradlew benchmark                               full run, results published in docs/benchmarks
 *   ./gradlew benchmark -Pbenchmark.quick=true        smoke run, results in benchmarks/build/benchmarks
 *   -Pbenchmark.targets=jvm,js,wasmJs,wasmWasi,native  subset of targets (default: all)
 *   -Pbenchmark.machine="My laptop"                   machine label (default: the CPU model)
 *   -Pbenchmark.jvm=25                                JVM version used to run the JVM benchmarks
 */

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.kotlin.qa)
}

repositories {
    mavenCentral()
}

val quick: Boolean = providers.gradleProperty("benchmark.quick")
    .map(String::toBoolean).getOrElse(false)
val benchmarkJvm: Int = providers.gradleProperty("benchmark.jvm")
    .map(String::toInt).getOrElse(25)
val selectedTargets: Set<String> = providers.gradleProperty("benchmark.targets")
    .map { it.split(',').map(String::trim).filter(String::isNotEmpty).toSet() }
    .getOrElse(setOf("jvm", "js", "wasmJs", "wasmWasi", "native"))

/*
 * Configuration compiled into the benchmark programs:
 * passing arguments is not uniformly supported across targets (e.g., WASI).
 */
val generateBenchmarkConfig = tasks.register("generateBenchmarkConfig") {
    group = "benchmark"
    description = "Generates the configuration compiled into the benchmark programs."
    val outputDirectory = layout.buildDirectory.dir("generated/benchmarkConfig/commonMain/kotlin")
    val warmupMillis = if (quick) 50 else 1_000
    val rounds = if (quick) 3 else 7
    val roundMillis = if (quick) 20 else 250
    inputs.property("quick", quick)
    outputs.dir(outputDirectory)
    doLast {
        val directory = outputDirectory.get().asFile.resolve("org/danilopianini/noncryptohash/benchmarks")
        directory.mkdirs()
        directory.resolve("BenchmarkConfig.kt").writeText(
            """
            |package org.danilopianini.noncryptohash.benchmarks
            |
            |/**
            | * Generated by Gradle: do not edit.
            | */
            |internal object BenchmarkConfig {
            |    const val QUICK: Boolean = $quick
            |    const val WARMUP_MILLIS: Long = $warmupMillis
            |    const val ROUNDS: Int = $rounds
            |    const val ROUND_MILLIS: Long = $roundMillis
            |}
            |
            """.trimMargin(),
        )
    }
}

kotlin {
    jvmToolchain(benchmarkJvm)
    jvm()
    js {
        nodejs()
        binaries.executable()
    }
    wasmJs {
        nodejs()
        binaries.executable()
    }
    wasmWasi {
        nodejs()
        binaries.executable()
    }
    val hostOs = System.getProperty("os.name")
    val hostArch = System.getProperty("os.arch")
    val nativeTarget: KotlinNativeTarget? = when {
        hostOs == "Linux" && hostArch in setOf("amd64", "x86_64") -> linuxX64()
        hostOs == "Linux" && hostArch == "aarch64" -> linuxArm64()
        hostOs.startsWith("Mac") && hostArch == "aarch64" -> macosArm64()
        hostOs.startsWith("Windows") -> mingwX64()
        else -> null
    }
    nativeTarget?.binaries?.executable(listOf(NativeBuildType.RELEASE)) {
        entryPoint = "org.danilopianini.noncryptohash.benchmarks.main"
    }
    applyDefaultHierarchyTemplate()
    sourceSets {
        commonMain {
            kotlin.srcDir(generateBenchmarkConfig)
            dependencies {
                implementation(project(":"))
            }
        }
    }
    targets.all {
        compilations.all {
            compileTaskProvider.configure {
                compilerOptions {
                    allWarningsAsErrors = true
                }
            }
        }
    }
}

