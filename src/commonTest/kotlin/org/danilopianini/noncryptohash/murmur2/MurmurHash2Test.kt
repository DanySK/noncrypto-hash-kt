    fun `keys hash as in the partitioner of Apache Kafka`() {
        // The cases of Kafka's UtilsTest.testMurmur2
        mapOf(
            "21" to -973932308,
            "foobar" to -790332482,
            "a-little-bit-long-string" to -985981536,
            "a-little-bit-longer-string" to -1486304829,
            "lkjh234lh9fiuh90y23oiuhsafujhadof229phr9h19h89h8" to -58897971,
            "abc" to 479470107,
        ).forEach { (key, hash) ->
            assertEquals(hash, MurmurHash2(MurmurHash2.KAFKA_SEED).hashInt(key.encodeToByteArray()), key)
        }
