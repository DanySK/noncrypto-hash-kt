    @Test
    fun `the hash matches the test vector of the specification`() {
        // Key 00 01 .. 0f, message 00 01 .. 0e (Appendix A of the specification)
        val message = ByteArray(15) { it.toByte() }
        assertEquals(
            -0x5ed6_359e_b641_ba1bL,
            SipHash24(0x0706_0504_0302_0100L, 0x0f0e_0d0c_0b0a_0908L).hashLong(message),
        )
    }

